//! Embed what `rcms new` writes, reading only files inside this crate, so
//! the published crate builds on its own (`cargo install rcms-scaffold`).
//!
//! - `RUSTANGO_REQ`: the framework requirement generated projects use, from
//!   `[package.metadata.rcms-scaffold] rustango` in this crate's manifest. A
//!   test checks it against the workspace's own requirement.
//! - `RCMS_REQ`: the rustango-cms requirement, this crate's `major.minor`
//!   (the scaffolder is released in step with rustango-cms).
//! - `THEME_FILES`: every text file under `themes/`; `THEME_PICTURES`: the
//!   sample pictures (`.jpg`, `.png`) as bytes.
//!
//! The CMS migrations are not embedded: a generated project writes them
//! from its rustango-cms dependency at every start
//! (`rustango_cms::migrations::materialize`), so they always match the
//! version it builds against.

use std::path::{Path, PathBuf};

fn main() {
    let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut out = String::from("// @generated by build.rs.\n");

    let manifest_path = crate_dir.join("Cargo.toml");
    println!("cargo:rerun-if-changed={}", manifest_path.display());
    let manifest = std::fs::read_to_string(&manifest_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", manifest_path.display()));
    let rustango_req = metadata_value(&manifest, "rustango")
        .expect("Cargo.toml declares `[package.metadata.rcms-scaffold] rustango = \"…\"`");
    out.push_str(&format!("const RUSTANGO_REQ: &str = {rustango_req:?};\n"));

    let version = std::env::var("CARGO_PKG_VERSION").expect("CARGO_PKG_VERSION");
    let rcms_req = version.splitn(3, '.').take(2).collect::<Vec<_>>().join(".");
    out.push_str(&format!("const RCMS_REQ: &str = {rcms_req:?};\n"));

    let themes = crate_dir.join("themes");
    println!("cargo:rerun-if-changed={}", themes.display());
    let mut theme_files = Vec::new();
    collect_files(&themes, &mut theme_files);
    theme_files.sort();
    // Text files (theme.json, templates) and pictures (`.jpg`, `.png`) apart:
    // pictures are bytes.
    let rel = |path: &Path| {
        path.strip_prefix(&themes)
            .expect("theme file under themes/")
            .to_string_lossy()
            .replace('\\', "/")
    };
    let is_picture = |path: &Path| path.extension().is_some_and(|e| e == "jpg" || e == "png");
    out.push_str("const THEME_FILES: &[(&str, &str)] = &[\n");
    for path in theme_files.iter().filter(|p| !is_picture(p)) {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!("    ({:?}, include_str!({:?})),\n", rel(path), path.display().to_string()));
    }
    out.push_str("];\nconst THEME_PICTURES: &[(&str, &[u8])] = &[\n");
    for path in theme_files.iter().filter(|p| is_picture(p)) {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!("    ({:?}, include_bytes!({:?})),\n", rel(path), path.display().to_string()));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR set by cargo")).join("generated.rs");
    std::fs::write(&dest, out).expect("write generated.rs");
}

/// `key = "value"` under `[package.metadata.rcms-scaffold]`.
fn metadata_value(manifest: &str, key: &str) -> Option<String> {
    let mut in_table = false;
    for line in manifest.lines().map(str::trim) {
        if line.starts_with('[') {
            in_table = line == "[package.metadata.rcms-scaffold]";
            continue;
        }
        if !in_table {
            continue;
        }
        let Some((k, v)) = line.split_once('=') else { continue };
        if k.trim() == key {
            return v.trim().strip_prefix('"')?.split('"').next().map(str::to_owned);
        }
    }
    None
}

/// Every file below `dir`, recursively.
fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let entries = std::fs::read_dir(dir).unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()));
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        if path.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            collect_files(&path, out);
        } else {
            out.push(path);
        }
    }
}
